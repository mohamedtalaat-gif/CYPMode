"""Build every illustration: ``python docs/figures/build_all.py``.

Imports the generator modules in ``docs/figures/gen/``, draws each catalogued figure (light and dark SVG and PNG, and the light and dark animation of a
dynamic process), checks that nothing catalogued is missing and that no figure file exists that is not catalogued, and writes ``CATALOG.md``.
"""

import importlib
import sys
import traceback
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE.parents[1]))

from catalog import REGISTRY, caption_text
from style import save


def load_generators() -> None:
    for path in sorted((HERE / "gen").glob("*.py")):
        if path.name != "__init__.py":
            importlib.import_module(f"gen.{path.stem}")


def figure_id_of(path: Path) -> str:
    """The figure id a produced file belongs to: ``<id>-light.svg``, ``<id>-dark.svg``, ``<id>-light.png``, ``<id>-dark.png``, ``<id>-anim-light.gif`` or ``<id>-anim-dark.gif``."""
    name = path.name
    for suffix in ("-light.svg", "-dark.svg", "-light.png", "-dark.png", "-anim-light.gif", "-anim-dark.gif"):
        if name.endswith(suffix):
            return name.removesuffix(suffix)
    return path.stem


def build() -> int:
    load_generators()
    failures = []
    for fig in REGISTRY.values():
        try:
            fig.files = save(fig.make, fig.group, fig.figure_id)
            if fig.animation is not None:
                fig.files += [fig.animation(theme) for theme in ("light", "dark")]
            print(f"ok   {fig.figure_id}")
        except Exception:
            failures.append(fig.figure_id)
            print(f"FAIL {fig.figure_id}\n{traceback.format_exc()}")
    produced = {figure_id_of(p) for g in {f.group for f in REGISTRY.values()} for p in (HERE / g).glob("*") if p.suffix in (".svg", ".png", ".gif")}
    stray = sorted(produced - set(REGISTRY))
    write_catalog()
    if not failures:
        from cypmode.audit.artifacts import record

        record("figures", [f for fig in REGISTRY.values() for f in fig.files if f.suffix in (".svg", ".png", ".gif")])
    if stray:
        print("figure files that are not catalogued:", stray)
    return 1 if failures or stray else 0


def write_catalog() -> None:
    lines = ["# Figure catalog", "", "Generated by `docs/figures/build_all.py` from `docs/figures/catalog.py`; do not edit by hand.", ""]
    groups: dict[str, list] = {}
    for fig in REGISTRY.values():
        groups.setdefault(fig.group, []).append(fig)
    for group, figs in groups.items():
        lines += [f"## {group}", ""]
        for fig in figs:
            lines += [f"### {fig.figure_id}: {fig.title}", "", caption_text(fig), "", f"- notebook section: {fig.section or 'n/a'}", f"- data: {', '.join(fig.data) or 'none (drawn from equations)'}",
                      f"- files: {', '.join(f.name for f in fig.files)}", ""]
    (HERE / "CATALOG.md").write_text("\n".join(lines))


if __name__ == "__main__":
    sys.exit(build())
