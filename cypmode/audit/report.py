"""Generate the audit report: ``python -m cypmode.audit.report --out audit/AUDIT_REPORT.md [--skip-tests]``.

Every number in the report is computed when this runs. The output has no timestamps, durations or temp
paths, so two runs on the same repository state are byte-identical (``scripts/run_audit.sh`` checks that).
"""

import argparse
import re
from pathlib import Path

import pandas as pd

from cypmode import data_record
from cypmode.audit import sections
from cypmode.audit.core import ROOT, Context, md_table


def build(skip_tests: bool = False, n_jobs: int = 2) -> str:
    ctx = Context(n_jobs)
    done = []
    for fn in sections.ALL:
        done.append(fn(ctx, enabled=not skip_tests) if fn is sections.tests else fn(ctx))
    summary = pd.DataFrame([(c.name, c.status, c.detail) for sec in done for c in sec.checks], columns=["check", "status", "detail"])
    counts = summary["status"].value_counts().to_dict()
    head = [
        "# Automated audit report",
        "",
        "Generated by `python -m cypmode.audit.report`. Every number below was computed from the repository's current code, data and caches when the report was generated; the only hand-written text is the wording around them.",
        "",
        "## Check summary",
        "",
        "Counts: " + ", ".join(f"{k} = {counts.get(k, 0)}" for k in ("PASS", "FAIL", "INFO", "SKIP")),
        "",
        md_table(summary),
        "",
    ]
    body = []
    for sec in done:
        body += [f"## {sec.title}", "", *sec.body, ""]
    return "\n".join(head + body).rstrip() + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", default="audit/AUDIT_REPORT.md")
    parser.add_argument("--skip-tests", action="store_true", help="skip the (slow) test-suite section")
    parser.add_argument("--n-jobs", type=int, default=2)
    args = parser.parse_args()
    gone = data_record.missing(ROOT)
    if gone:
        raise SystemExit(data_record.message_for(gone))  # the inputs are named before the first one is read
    text = build(args.skip_tests, args.n_jobs)
    out = Path(args.out) if Path(args.out).is_absolute() else ROOT / args.out
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
    fails = re.findall(r"\| FAIL \|", text)
    print(f"wrote {out} ({len(text.splitlines())} lines); failed checks: {len(fails)}")


if __name__ == "__main__":
    main()
